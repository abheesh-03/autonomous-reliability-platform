#!/usr/bin/env bash
#
# init-remediation-secrets.sh — Phase 8 remediation secret setup.
#
# Manages SIX independent, never-interchangeable Bearer tokens, all
# written ONLY to .env (none of them is ever mirrored into a second
# file the way scripts/init-webhook-secret.sh's webhook token is --
# nothing outside this platform's own containers, which all read .env
# as plain environment variables via docker-compose.yml, ever needs a
# separate copy):
#
#   CONTROL_PLANE_REMEDIATION_PROPOSAL_TOKEN  - held ONLY by
#       agent-runtime-service. Authorizes creating a remediation
#       proposal only.
#   CONTROL_PLANE_REMEDIATION_APPROVER_TOKEN  - held ONLY by a
#       human/operator (or a CI acceptance script simulating one, see
#       scripts/verify-remediation.sh). Authorizes approving/rejecting
#       a proposal only. NEVER given to agent-runtime-service,
#       tool-gateway, investigator-service, or retrieval-service.
#   CONTROL_PLANE_REMEDIATION_EXECUTOR_TOKEN  - held ONLY by
#       tool-gateway. Authorizes recording execution start/result
#       only.
#   TOOL_GATEWAY_EXECUTION_TOKEN              - held by
#       agent-runtime-service (to ASK tool-gateway to execute) and by
#       tool-gateway itself (to verify that ask) -- this one token
#       authenticates calls INTO tool-gateway, not out of it; see
#       docs/architecture/phase-8-human-approval-remediation.md.
#   PAYMENT_FAULT_INJECTION_TOKEN             - held ONLY by the
#       test/operator failure-injection path (scripts/verify-remediation.sh).
#       tool-gateway must NEVER receive this token.
#   PAYMENT_REMEDIATION_TOKEN                 - held ONLY by
#       tool-gateway. This is the ONE payment-service credential it
#       gets -- it authorizes clearing/reading the controlled fault,
#       never enabling it.
#
# Local-development security, not a production secrets framework --
# same honest framing as scripts/init-webhook-secret.sh.
#
# Idempotent and safe to rerun: .env is authoritative for every one of
# these six lines. An existing, non-empty value is NEVER regenerated
# or overwritten. Never prints any token value to stdout/stderr.
#
# Safe on a fresh checkout (.env may not exist yet) and on a
# pre-existing local .env (never touches any OTHER existing variable;
# only ever adds or replaces its own six lines).
#
# Fails closed (refuses to declare success) if any two of these six
# tokens -- or any one of them and the EXISTING
# CONTROL_PLANE_WEBHOOK_TOKEN/CONTROL_PLANE_LIFECYCLE_TOKEN -- end up
# identical. Mirrors control_plane.core.config.resolve_write_tokens's
# own independent, application-level guard against this same
# misconfiguration if this initializer is ever bypassed.

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." &>/dev/null && pwd)"
cd "$REPO_ROOT"

ENV_FILE=".env"

fail() {
  echo "FAIL: $1" >&2
  exit 1
}

if [ ! -f "$ENV_FILE" ]; then
  cp .env.example "$ENV_FILE"
  echo "created $ENV_FILE from .env.example"
fi

# ensure_token NAME COMMENT_LINES...
# Reads the existing value of NAME from .env (empty if unset/blank).
# If non-empty, leaves it untouched. Otherwise generates a fresh
# 256-bit hex token and appends (or replaces an existing-but-empty
# line for) NAME=... Always leaves the resolved value in the global
# variable `_ensured_value` for the caller's own distinctness checks.
ensure_token() {
  local name="$1"
  shift
  local existing
  existing="$(grep -E "^${name}=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- || true)"

  if [ -n "$existing" ]; then
    _ensured_value="$existing"
    echo "$name already set in $ENV_FILE — leaving it unchanged."
    return 0
  fi

  local generated
  generated="$(python3 -c 'import secrets; print(secrets.token_hex(32))')"
  echo "generated a new $name"

  if grep -qE "^${name}=" "$ENV_FILE"; then
    local tmp
    tmp="$(mktemp)"
    sed "s|^${name}=.*|${name}=${generated}|" "$ENV_FILE" > "$tmp"
    mv "$tmp" "$ENV_FILE"
  else
    {
      echo ""
      for line in "$@"; do
        echo "# $line"
      done
      echo "${name}=${generated}"
    } >> "$ENV_FILE"
  fi

  _ensured_value="$generated"
}

ensure_token CONTROL_PLANE_REMEDIATION_PROPOSAL_TOKEN \
  "Phase 8: held ONLY by agent-runtime-service -- create a remediation" \
  "proposal only. Generated by scripts/init-remediation-secrets.sh;" \
  "never rotated automatically -- delete this line and rerun the" \
  "script to force a new value."
proposal_token="$_ensured_value"

ensure_token CONTROL_PLANE_REMEDIATION_APPROVER_TOKEN \
  "Phase 8: held ONLY by a human/operator (or a CI acceptance script" \
  "simulating one) -- approve/reject a proposal only. NEVER given to" \
  "agent-runtime-service, tool-gateway, investigator-service, or" \
  "retrieval-service."
approver_token="$_ensured_value"

ensure_token CONTROL_PLANE_REMEDIATION_EXECUTOR_TOKEN \
  "Phase 8: held ONLY by tool-gateway -- record execution start/result" \
  "only. Cannot create or approve/reject a proposal."
executor_token="$_ensured_value"

ensure_token TOOL_GATEWAY_EXECUTION_TOKEN \
  "Phase 8: authenticates calls INTO tool-gateway. Held by" \
  "agent-runtime-service (to ask tool-gateway to execute an approved" \
  "action, and to read tool-gateway's read-only remediation-capability" \
  "precondition endpoint) and by tool-gateway itself (to verify that" \
  "ask). This token alone never authorizes an action -- tool-gateway" \
  "independently re-verifies control-plane's own approved proposal" \
  "record on every call."
tool_gateway_token="$_ensured_value"

ensure_token PAYMENT_FAULT_INJECTION_TOKEN \
  "Phase 8: held ONLY by the test/operator failure-injection path" \
  "(scripts/verify-remediation.sh). tool-gateway must NEVER receive" \
  "this token."
fault_injection_token="$_ensured_value"

ensure_token PAYMENT_REMEDIATION_TOKEN \
  "Phase 8: held ONLY by tool-gateway -- the ONE payment-service" \
  "credential it gets. Authorizes clearing/reading the controlled" \
  "authorization fault only -- never enabling it."
payment_remediation_token="$_ensured_value"

ensure_token CONTROL_PLANE_INTERNAL_READ_TOKEN_AGENT_RUNTIME \
  "Phase 14 correction round, Issue 3: agent-runtime-service's own" \
  "distinct, bounded internal-service-read identity for control-plane's" \
  "GET routes (incidents/evidence/remediation-proposal reads) -- never" \
  "usable for the human-approval decision endpoint."
control_plane_internal_read_token_agent_runtime="$_ensured_value"

ensure_token CONTROL_PLANE_INTERNAL_READ_TOKEN_INVESTIGATOR \
  "Phase 14 correction round, Issue 3: investigator-service's own" \
  "distinct internal-service-read identity for control-plane's GET" \
  "routes."
control_plane_internal_read_token_investigator="$_ensured_value"

ensure_token CONTROL_PLANE_INTERNAL_READ_TOKEN_TOOL_GATEWAY \
  "Phase 14 correction round, Issue 3: tool-gateway's own distinct" \
  "internal-service-read identity for control-plane's" \
  "GET /api/v1/remediation-proposals/{id} (its own independent" \
  "proposal-status re-verification before executing anything)."
control_plane_internal_read_token_tool_gateway="$_ensured_value"

ensure_token INVESTIGATOR_INTERNAL_READ_TOKEN_AGENT_RUNTIME \
  "Phase 14 correction round, Issue 2/3: what agent-runtime-service" \
  "presents TO investigator-service -- closes 'a direct HTTP call to" \
  "investigator-service's own exposed port bypasses the frontend'."
investigator_internal_read_token_agent_runtime="$_ensured_value"

ensure_token RETRIEVAL_INTERNAL_READ_TOKEN_INVESTIGATOR \
  "Phase 14 correction round, Issue 2/3: what investigator-service" \
  "presents TO retrieval-service -- closes 'a direct HTTP call to" \
  "retrieval-service's own exposed port bypasses investigator-service'."
retrieval_internal_read_token_investigator="$_ensured_value"

chmod 600 "$ENV_FILE"

# --------------------------------------------------------------------
# Cross-token distinctness (fail closed): every one of these six, AND
# the two pre-existing webhook/lifecycle tokens, must be pairwise
# distinct. A naive hand-edit of .env (pasting the same value into two
# lines) is the real, plausible risk this guards against -- the same
# reasoning scripts/init-webhook-secret.sh already documents for its
# own two tokens.
# --------------------------------------------------------------------
existing_webhook_token="$(grep -E '^CONTROL_PLANE_WEBHOOK_TOKEN=' "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- || true)"
existing_lifecycle_token="$(grep -E '^CONTROL_PLANE_LIFECYCLE_TOKEN=' "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- || true)"

all_names=(
  CONTROL_PLANE_WEBHOOK_TOKEN
  CONTROL_PLANE_LIFECYCLE_TOKEN
  CONTROL_PLANE_REMEDIATION_PROPOSAL_TOKEN
  CONTROL_PLANE_REMEDIATION_APPROVER_TOKEN
  CONTROL_PLANE_REMEDIATION_EXECUTOR_TOKEN
  TOOL_GATEWAY_EXECUTION_TOKEN
  PAYMENT_FAULT_INJECTION_TOKEN
  PAYMENT_REMEDIATION_TOKEN
  CONTROL_PLANE_INTERNAL_READ_TOKEN_AGENT_RUNTIME
  CONTROL_PLANE_INTERNAL_READ_TOKEN_INVESTIGATOR
  CONTROL_PLANE_INTERNAL_READ_TOKEN_TOOL_GATEWAY
  INVESTIGATOR_INTERNAL_READ_TOKEN_AGENT_RUNTIME
  RETRIEVAL_INTERNAL_READ_TOKEN_INVESTIGATOR
)
all_values=(
  "$existing_webhook_token"
  "$existing_lifecycle_token"
  "$proposal_token"
  "$approver_token"
  "$executor_token"
  "$tool_gateway_token"
  "$fault_injection_token"
  "$payment_remediation_token"
  "$control_plane_internal_read_token_agent_runtime"
  "$control_plane_internal_read_token_investigator"
  "$control_plane_internal_read_token_tool_gateway"
  "$investigator_internal_read_token_agent_runtime"
  "$retrieval_internal_read_token_investigator"
)

count=${#all_names[@]}
i=0
while [ "$i" -lt "$count" ]; do
  j=$((i + 1))
  while [ "$j" -lt "$count" ]; do
    vi="${all_values[$i]}"
    vj="${all_values[$j]}"
    if [ -n "$vi" ] && [ -n "$vj" ] && [ "$vi" = "$vj" ]; then
      fail "${all_names[$i]} and ${all_names[$j]} are configured identically. These authenticate separate, non-interchangeable write paths and must never share a value. Edit .env by hand to give one of them a different value, or delete the line and rerun this script to generate a fresh, independently random token. (values not shown)"
    fi
    j=$((j + 1))
  done
  i=$((i + 1))
done

echo "remediation secrets ready: $ENV_FILE holds all six Phase 8 tokens plus the five Phase 14 internal-service-read tokens, pairwise distinct from each other and from the existing webhook/lifecycle tokens (values not printed)."
